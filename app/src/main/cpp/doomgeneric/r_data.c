static int R_ColorDistSq(const byte *pal, int c1, int c2)
{
    int dr = (int)pal[c1 * 3 + 0] - (int)pal[c2 * 3 + 0];
    int dg = (int)pal[c1 * 3 + 1] - (int)pal[c2 * 3 + 1];
    int db = (int)pal[c1 * 3 + 2] - (int)pal[c2 * 3 + 2];
    // Perceptual YUV-weighted RGB distance
    return (dr * dr * 3) + (dg * dg * 4) + (db * db * 2);
}

void R_InitUpscaleTables (void)
{
    int r, g, b, i, j;
    const byte *pal = (const byte *)W_CacheLumpName(DEH_String("PLAYPAL"), PU_CACHE);

    // 1. Build 5-bit RGB (32x32x32) -> Closest PLAYPAL index lookup
    for (r = 0; r < 32; r++)
    {
        int rr = (r << 3) | (r >> 2);
        for (g = 0; g < 32; g++)
        {
            int gg = (g << 3) | (g >> 2);
            for (b = 0; b < 32; b++)
            {
                int bb = (b << 3) | (b >> 2);
                int bestIdx = 0;
                int bestDist = 0x7fffffff;
                for (i = 0; i < 256; i++)
                {
                    int dr = rr - (int)pal[i * 3 + 0];
                    int dg = gg - (int)pal[i * 3 + 1];
                    int db = bb - (int)pal[i * 3 + 2];
                    int dist = (dr * dr * 3) + (dg * dg * 4) + (db * db * 2);
                    if (dist < bestDist)
                    {
                        bestDist = dist;
                        bestIdx = i;
                        if (dist == 0) break;
                    }
                }
                r_rgb_to_pal[r][g][b] = (byte)bestIdx;
            }
        }
    }

    // 2. Build 256x256 PLAYPAL perceptual blend & similarity tables
    for (i = 0; i < 256; i++)
    {
        int r1 = pal[i * 3 + 0];
        int g1 = pal[i * 3 + 1];
        int b1 = pal[i * 3 + 2];

        for (j = 0; j < 256; j++)
        {
            int r2 = pal[j * 3 + 0];
            int g2 = pal[j * 3 + 1];
            int b2 = pal[j * 3 + 2];

            int m50_r = (r1 + r2) >> 4;
            int m50_g = (g1 + g2) >> 4;
            int m50_b = (b1 + b2) >> 4;
            r_pal_blend50[i][j] = r_rgb_to_pal[m50_r][m50_g][m50_b];

            int m75_r = (r1 * 3 + r2) >> 5;
            int m75_g = (g1 * 3 + g2) >> 5;
            int m75_b = (b1 * 3 + b2) >> 5;
            r_pal_blend75[i][j] = r_rgb_to_pal[m75_r][m75_g][m75_b];

            // Perceptually similar colors (same color ramp / subtle shading step)
            r_pal_sim[i][j] = (R_ColorDistSq(pal, i, j) <= 6800) ? 1 : 0;
        }
    }

    if (numflats > 0)
    {
        upscaled_flats = (byte **)Z_Malloc(numflats * sizeof(byte *), PU_STATIC, NULL);
        memset(upscaled_flats, 0, numflats * sizeof(byte *));
    }
}

// Seamless toroidal 2x Edge-Directed (xBR/EPX + Perceptual Shading) tile upscaler
static void R_UpscaleTile2x(const byte *src, byte *dst, int N)
{
    int mask = N - 1;
    int dstN = N * 2;
    int y, x;

    for (y = 0; y < N; y++)
    {
        int ym1 = (y - 1) & mask;
        int yp1 = (y + 1) & mask;

        for (x = 0; x < N; x++)
        {
            int xm1 = (x - 1) & mask;
            int xp1 = (x + 1) & mask;

            byte A = src[ym1 * N + xm1];
            byte B = src[ym1 * N + x];
            byte C = src[ym1 * N + xp1];
            byte D = src[y   * N + xm1];
            byte P = src[y   * N + x];
            byte F = src[y   * N + xp1];
            byte G = src[yp1 * N + xm1];
            byte H = src[yp1 * N + x];
            byte I = src[yp1 * N + xp1];

            byte E0 = P, E1 = P, E2 = P, E3 = P;

            // Top-Left (E0): D, B, A
            if ((D == B || r_pal_sim[D][B]) && !r_pal_sim[D][H] && !r_pal_sim[B][F])
            {
                byte diag = r_pal_blend50[D][B];
                E0 = (P != A) ? r_pal_blend75[diag][P] : r_pal_blend50[diag][P];
            }
            else if (r_pal_sim[P][D] && r_pal_sim[P][B])
            {
                E0 = r_pal_blend75[P][r_pal_blend50[D][B]];
            }

            // Top-Right (E1): F, B, C
            if ((F == B || r_pal_sim[F][B]) && !r_pal_sim[F][H] && !r_pal_sim[B][D])
            {
                byte diag = r_pal_blend50[F][B];
                E1 = (P != C) ? r_pal_blend75[diag][P] : r_pal_blend50[diag][P];
            }
            else if (r_pal_sim[P][F] && r_pal_sim[P][B])
            {
                E1 = r_pal_blend75[P][r_pal_blend50[F][B]];
            }

            // Bottom-Left (E2): D, H, G
            if ((D == H || r_pal_sim[D][H]) && !r_pal_sim[D][B] && !r_pal_sim[H][F])
            {
                byte diag = r_pal_blend50[D][H];
                E2 = (P != G) ? r_pal_blend75[diag][P] : r_pal_blend50[diag][P];
            }
            else if (r_pal_sim[P][D] && r_pal_sim[P][H])
            {
                E2 = r_pal_blend75[P][r_pal_blend50[D][H]];
            }

            // Bottom-Right (E3): F, H, I
            if ((F == H || r_pal_sim[F][H]) && !r_pal_sim[F][B] && !r_pal_sim[H][D])
            {
                byte diag = r_pal_blend50[F][H];
                E3 = (P != I) ? r_pal_blend75[diag][P] : r_pal_blend50[diag][P];
            }
            else if (r_pal_sim[P][F] && r_pal_sim[P][H])
            {
                E3 = r_pal_blend75[P][r_pal_blend50[F][H]];
            }

            dst[(y * 2)     * dstN + (x * 2)]     = E0;
            dst[(y * 2)     * dstN + (x * 2 + 1)] = E1;
            dst[(y * 2 + 1) * dstN + (x * 2)]     = E2;
            dst[(y * 2 + 1) * dstN + (x * 2 + 1)] = E3;
        }
    }
}

byte *R_GetUpscaledFlat (int flatnum)
{
    byte *src64;
    byte *mid128;
    byte *dst256;

    if (flatnum < 0 || flatnum >= numflats || !upscaled_flats)
    {
        return (byte *)W_CacheLumpNum(firstflat + flatnum, PU_CACHE);
    }

    if (upscaled_flats[flatnum] != NULL)
    {
        return upscaled_flats[flatnum];
    }

    // Pin source lump as PU_STATIC before allocating work buffers so Z_Malloc cannot purge src64
    src64 = (byte *)W_CacheLumpNum(firstflat + flatnum, PU_STATIC);
    mid128 = (byte *)Z_Malloc(128 * 128, PU_STATIC, NULL);
    dst256 = (byte *)Z_Malloc(256 * 256, PU_STATIC, &upscaled_flats[flatnum]);

    // 2-stage edge-directed super-resolution: 64x64 -> 128x128 -> 256x256
    R_UpscaleTile2x(src64, mid128, 64);
    W_ReleaseLumpNum(firstflat + flatnum);

    R_UpscaleTile2x(mid128, dst256, 128);
    Z_Free(mid128);

    // Demote to PU_CACHE so the zone allocator can evict and clear upscaled_flats[flatnum] under pressure
    Z_ChangeTag(dst256, PU_CACHE);
    return dst256;
}





